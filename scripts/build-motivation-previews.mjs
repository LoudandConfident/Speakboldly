// Build small social-preview derivatives; original artwork stays untouched.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync,execFileSync} from 'node:child_process';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {dailyQuotes} from '../home-gallery.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),target=resolve(root,'motivation-preview-images.js');
let previous={};if(existsSync(target)){const text=readFileSync(target,'utf8');try{previous=JSON.parse(text.slice(text.indexOf('=')+1).trim().replace(/;$/,''));}catch{}}
const result={};
for(const entry of dailyQuotes){
 const source=resolve(root,entry.image),version=createHash('sha256').update(readFileSync(source)).update('jpeg-600-v1').digest('hex').slice(0,12);
 const stem=entry.image.split('/').pop().replace(/\.png$/,''),image='./images/motivation-preview/'+stem+'-'+version+'.jpg',destination=resolve(root,image);
 if(previous[entry.image]?.version===version&&existsSync(destination)){result[entry.image]=previous[entry.image];continue;}
 const modern=spawnSync('magick',['-version'],{stdio:'ignore'}).status===0,command=modern?'magick':'convert';
 mkdirSync(dirname(destination),{recursive:true});
 execFileSync(command,[source,'-auto-orient','-thumbnail','600x600>','-strip','-quality','80',destination]);
 const size=execFileSync(modern?'magick':'identify',modern?['identify','-format','%w %h',destination]:['-format','%w %h',destination],{encoding:'utf8'}).trim().split(' ').map(Number);
 const bytes=readFileSync(destination).length;if(bytes>200000)throw Error('Preview exceeds the 200 KB budget: '+image);
 result[entry.image]={image,width:size[0],height:size[1],version,bytes};
}
writeFileSync(target,'// Generated by scripts/build-motivation-previews.mjs. Original pictures are unchanged.\nexport const motivationPreviews = '+JSON.stringify(result,null,2)+';\n');
console.log('Built '+Object.keys(result).length+' small picture previews. Largest: '+Math.max(...Object.values(result).map(item=>item.bytes))+' bytes.');
